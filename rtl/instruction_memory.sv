module instruction_memory(/*AUTOARG*/
			  // Outputs
			  instr,
			  // Inputs
			  pc
			  );
   input logic [5:0] pc;
   output logic [17:0] instr;

   logic [17:0]	       Memory [0:35];

   always_comb begin
      //-------------
      Memory[0] = 18'b 0101_0000_0000_000000; //stall

      Memory[1] = 18'b 1110_0000_0000_000000;     //load1
      Memory[2] = 18'b 1110_0000_0000_000000;
      Memory[3] = 18'b 1110_0000_0000_000000;
      Memory[4] = 18'b 1110_0000_0000_000000;
      Memory[5] = 18'b 1110_0000_0000_000000;
      Memory[6] = 18'b 1110_0000_0000_000000;
      Memory[7] = 18'b 1110_0000_0000_000000;
      Memory[8] = 18'b 1110_0000_0000_000000;
      Memory[9] = 18'b 1110_0000_0000_000000;

      Memory[10] = 18'b 0000_0111_1011_000001;    //add $t1, $t7 ,$t11

      //         ----------up, down, right, left   load2-----------------------
      Memory[11] = 18'b 1111_0000_0000_000000;

      //------------calculate---------------------
      Memory[12] = 18'b 0000_0001_0010_000001;    //add  $t1, $t1, $t2
      Memory[13] = 18'b 0000_0001_0011_000001;    //add  $t1, $t1, $t3
      Memory[14] = 18'b 0000_0001_0100_000001;    //add  $t1, $t1, $t4
      Memory[15] = 18'b 0000_0001_0101_000001;    //add  $t1, $t1, $t5
      Memory[16] = 18'b 0001_0001_0110_000001;    //div  $t1, $t1, $t6
      Memory[17] = 18'b 0000_0001_1011_000111;    //shift  $t7 <-- $t1
      //


      //      ----------up, down, right, left   load2-----------------------
      Memory[18] = 18'b 1111_0000_0000_000000;

      //연산완료 신호 1로 update
      Memory[19] = 18'b 0000_1011_1000_001100;  // add $12, $11, $8

      Memory[20] = 18'b 1110_0000_0000_000000;    //load1 (shift out)
      Memory[21] = 18'b 1110_0000_0000_000000;
      Memory[22] = 18'b 1110_0000_0000_000000;
      Memory[23] = 18'b 1110_0000_0000_000000;
      Memory[24] = 18'b 1110_0000_0000_000000;
      Memory[25] = 18'b 1110_0000_0000_000000;
      Memory[26] = 18'b 1110_0000_0000_000000;
      Memory[27] = 18'b 1110_0000_0000_000000;
      Memory[28] = 18'b 1110_0000_0000_000000;

      //연산완료 신호 0으로 update
      Memory[29] = 18'b 0000_1011_1011_001100;  // add $12, $11, $11


      Memory[30] = 18'b 0000_1010_1000_001010;    //add $t10 $t10 $t8
      Memory[31] = 18'b 0010_1001_1010_100001;    //beq $t9, $t10, 33
      Memory[32] = 18'b 0100_0000_0000_001100;    //jump to Mem[12]
      Memory[33] = 18'b 0100_0000_0000_100001;    //jump self
   end
   assign instr = Memory[pc];


endmodule // instruction_memory
